import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { bundledLanguages, bundledLanguagesAlias } from "shiki";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const names = [
  ...new Set([...Object.keys(bundledLanguages), ...Object.keys(bundledLanguagesAlias)]),
].sort();
const entries = names.map((name) => `    ${JSON.stringify(name)},`).join("\n");
const source = `// Generated by scripts/generate-language-catalog.mjs. Do not edit by hand.\n// This startup-safe catalog replaces Shiki's eager bundled-language registry import.\nexport const BUNDLED_SYNTAX_LANGUAGE_NAMES: ReadonlySet<string> = new Set([\n${entries}\n]);\n`;
const outputPath = path.join(packageRoot, "src", "syntax", "bundled-language-names.ts");
if (process.argv.includes("--check")) {
  const existing = await readFile(outputPath, "utf8");
  if (existing !== source) {
    throw new Error("Shiki language catalog is stale; run npm run language-catalog:generate");
  }
} else {
  await writeFile(outputPath, source);
}
